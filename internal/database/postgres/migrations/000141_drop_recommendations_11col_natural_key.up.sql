-- Migration 000141: drop the 11-column recommendations_natural_key_az_tp_idx
-- and the 12-column recommendations_natural_key_source_idx (#408, contract step
-- of the RDS AZ-config identity work).
--
-- Migration 000140 added the generated az_config column, the 12-column
-- recommendations_natural_key_az_tp_azc_idx and the 13-column
-- recommendations_natural_key_source_azc_idx, and kept the indexes without
-- az_config so the previous upsert (ON CONFLICT on the 11 columns) kept
-- working. The store now upserts on the 12-column index, so both indexes
-- without az_config only do harm: they reject a Single-AZ and a Multi-AZ RDS
-- row of the same class, engine, term and payment, which aborts the whole
-- collection write. Dropping them lets those rows coexist. The 000120 source
-- index is superseded by recommendations_natural_key_source_azc_idx (the same
-- key plus az_config), so the source-account work of #799 keeps a
-- source-aware unique key.
--
-- DEPLOY ORDER: apply this only after the code that upserts on the 12-column
-- index is live everywhere. Applying it while older code still runs breaks
-- every collection, because ON CONFLICT on the 11 columns needs that index.
-- database-migration.yml applies ALL pending migrations when `steps` is 0 or
-- empty, so never dispatch it with the default before that code is released.
--
-- Each replacement index is strictly finer than the one it supersedes, so no
-- existing row can violate it and nothing needs backfilling.
DROP INDEX IF EXISTS recommendations_natural_key_az_tp_idx;
DROP INDEX IF EXISTS recommendations_natural_key_source_idx;
