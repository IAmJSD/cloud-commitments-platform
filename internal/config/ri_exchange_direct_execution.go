package config

import (
	"encoding/json"
	"errors"
	"fmt"
	"strings"

	"github.com/google/uuid"
)

// Statuses of an ri_exchange_direct_executions row (issue #82). A row is
// written as RIExchangeDirectStatusSubmitted before the provider call and
// moved exactly once to one of the three terminal statuses after it; see
// migration 000131 for what each one asserts about the money.
const (
	RIExchangeDirectStatusSubmitted = "submitted"
	RIExchangeDirectStatusCompleted = "completed"
	RIExchangeDirectStatusFailed    = "failed"
	RIExchangeDirectStatusUnknown   = "unknown"
)

// ErrRIExchangeDirectExecutionNotSubmitted is returned by
// FinalizeRIExchangeDirectExecution when the row does not exist or has
// already been finalized. The first recorded outcome stands: an audit row is
// never rewritten.
var ErrRIExchangeDirectExecutionNotSubmitted = errors.New("ri exchange direct execution is not awaiting an outcome")

// RIExchangeDirectExecution is the audit-trail record of one RI exchange
// executed directly through the API, as opposed to through the scheduled
// approve/reject flow that persists to ri_exchange_history (issue #82).
//
// The fields set before the provider call are inserted by
// SaveRIExchangeDirectExecution; the outcome is recorded once by
// FinalizeRIExchangeDirectExecution.
type RIExchangeDirectExecution struct {
	// ID is generated by the caller, so the caller can finalize the row
	// without depending on the store writing it back.
	ID       string `json:"id"`
	Provider string `json:"provider"`
	// CloudAccountID is the registered cloud account the exchange was
	// authorized against; nil when none is registered.
	CloudAccountID *string `json:"cloud_account_id,omitempty"`
	// ProviderAccountID is the Azure subscription ID; nil for AWS.
	ProviderAccountID *string `json:"provider_account_id,omitempty"`
	// Region is the AWS region; nil for Azure.
	Region    *string  `json:"region,omitempty"`
	SourceIDs []string `json:"source_ids"`
	// Sources is the submitted source list with per-source quantities, a
	// non-empty JSON array; nil for AWS, which exchanges whole RIs.
	Sources json.RawMessage `json:"sources,omitempty"`
	// Targets is the submitted target list, a non-empty JSON array.
	Targets            json.RawMessage `json:"targets"`
	MaxPaymentDue      string          `json:"max_payment_due"`
	MaxPaymentCurrency string          `json:"max_payment_currency"`
	// QuotedNetPayable is Azure's pre-execute re-quote; nil for AWS.
	QuotedNetPayable *string `json:"quoted_net_payable,omitempty"`
	// ProviderReference is the Azure session ID when known before the call.
	ProviderReference  string  `json:"provider_reference,omitempty"`
	ExecutedByUserID   *string `json:"executed_by_user_id,omitempty"`
	ExecutedBy         string  `json:"executed_by"`
	ExecutedByAPIKeyID *string `json:"executed_by_api_key_id,omitempty"`
}

// Validate rejects a record the table would refuse, so a malformed audit row
// fails before it can block an exchange on a database round trip, and with a
// message naming the field.
func (r *RIExchangeDirectExecution) Validate() error {
	if _, err := uuid.Parse(r.ID); err != nil {
		return fmt.Errorf("ri exchange direct execution id %q is not a UUID", r.ID)
	}
	if r.Provider != "aws" && r.Provider != "azure" {
		return fmt.Errorf("ri exchange direct execution provider %q is not aws or azure", r.Provider)
	}
	if err := r.validateExchangeShape(); err != nil {
		return err
	}
	if strings.TrimSpace(r.MaxPaymentDue) == "" || strings.TrimSpace(r.MaxPaymentCurrency) == "" {
		return errors.New("ri exchange direct execution has no spend cap")
	}
	if strings.TrimSpace(r.ExecutedBy) == "" {
		return errors.New("ri exchange direct execution has no executing identity")
	}
	return nil
}

// validateExchangeShape checks what was exchanged for what: the source IDs
// and the JSON source/target lists. Split from Validate for the gocyclo limit.
func (r *RIExchangeDirectExecution) validateExchangeShape() error {
	if len(r.SourceIDs) == 0 {
		return errors.New("ri exchange direct execution has no source ids")
	}
	if !isNonEmptyJSONArray(r.Targets) {
		return errors.New("ri exchange direct execution targets must be a non-empty JSON array")
	}
	if r.Sources != nil && !isNonEmptyJSONArray(r.Sources) {
		return errors.New("ri exchange direct execution sources must be absent or a non-empty JSON array")
	}
	return nil
}

func isNonEmptyJSONArray(raw json.RawMessage) bool {
	var elems []json.RawMessage
	return json.Unmarshal(raw, &elems) == nil && len(elems) > 0
}

// RIExchangeDirectOutcome is what the provider call produced, recorded once
// by FinalizeRIExchangeDirectExecution.
type RIExchangeDirectOutcome struct {
	// Status is one of the terminal RIExchangeDirectStatus* values.
	Status string
	// ProviderReference is the AWS exchange ID or the Azure session ID the
	// provider echoed; empty keeps the value recorded at submit time.
	ProviderReference string
	// NetPayable is the provider-reported net amount as a decimal string;
	// nil when the provider reported none.
	NetPayable         *string
	NetPayableCurrency string
	// ProviderStatus is Azure's operation status string.
	ProviderStatus string
	Error          string
}

// Validate rejects an outcome that is not terminal: finalizing a row back to
// "submitted" would erase the fact that its outcome was ever recorded.
func (o *RIExchangeDirectOutcome) Validate() error {
	switch o.Status {
	case RIExchangeDirectStatusCompleted, RIExchangeDirectStatusFailed, RIExchangeDirectStatusUnknown:
		return nil
	default:
		return fmt.Errorf("ri exchange direct execution outcome status %q is not terminal", o.Status)
	}
}
